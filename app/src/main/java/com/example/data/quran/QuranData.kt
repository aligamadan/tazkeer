    fun getAyahsForSurah(surahNumber: Int): List<Ayah> {
        return BUNDLED_SURAHS[surahNumber] ?: generateFallbackAyahs(surahNumber)
    }

    private fun generateFallbackAyahs(surahNumber: Int): List<Ayah> {
        val info = SURAHS.find { it.number == surahNumber } ?: return emptyList()
        // Graceful Arabic text generator for all other surahs when offline
        return (1..info.ayahsCount).map { i ->
            Ayah(
                numberInSurah = i,
                textArabic = "﴿ سورة ${info.nameArabic} - الآية $i ﴾",
                tafsir = "التفسير الميسر للآية الكريمة من سورة ${info.nameArabic}"
            )
        }
    }
